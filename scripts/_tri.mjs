import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: process.env.LOCALAPPDATA + '/ms-playwright/chromium-1228/chrome-win64/chrome.exe', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-gpu-watchdog'] })
const p = await b.newPage({ viewport: { width: 900, height: 540 } })
await p.addInitScript((q) => localStorage.setItem('pumpchad.chadverse.save', JSON.stringify({ version: 2, character: null, progress: { discoveries: ['intro_seen'], xp: 800 }, settings: { quality: q, muted: true } })), process.env.Q || 'medium')
await p.goto(`http://localhost:${process.env.PORT || 5180}/chadverse/?sky=day`)
await p.click('[data-testid=enter-muted]')
await p.waitForSelector('[role=tablist]')
await p.getByRole('tab', { name: 'Name' }).click()
await p.fill('#chad-name', 'Rider')
await p.getByRole('button', { name: /Enter Chad Square/ }).click()
await p.waitForFunction(() => window.__chadverse?.phase === 'world' && window.__chadverse.world(), null, { timeout: 120000 })
await p.evaluate(() => window.__chadverse.teleport(0, 34, 3.14))
await p.waitForTimeout(4000)
const r = await p.evaluate(() => ({ st: window.__chadverse.stats(), tb: window.__chadverse.triBreakdown(18) }))
console.log('stats', JSON.stringify(r.st))
console.log('scene total tris', r.tb.total, 'meshes', r.tb.meshes)
for (const t of r.tb.top) console.log(String(t.tris).padStart(8), 'x' + t.inst, t.geo, t.mat, JSON.stringify(t.at), t.lod ? 'LOD' : '')
await b.close()
