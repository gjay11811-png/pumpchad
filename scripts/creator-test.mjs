// Character selection: species cards (mouse, keyboard, touch), arrows, focus, saved choice, no extra renderer, no horizontal overflow. SIMULATED.
import { chromium, devices } from 'playwright'
const BASE = process.env.URL || 'http://localhost:5180/chadverse/'
const b = await chromium.launch({ executablePath: process.env.LOCALAPPDATA + '/ms-playwright/chromium-1228/chrome-win64/chrome.exe' })
let fails = 0
const check = (ok, msg) => { console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${msg}`); if (!ok) fails++ }
for (const [name, opts] of [['desktop', { viewport: { width: 1280, height: 720 } }], ['phone', { ...devices['iPhone 13'] }]]) {
  console.log(name)
  const ctx = await b.newContext(opts)
  const p = await ctx.newPage()
  const errs = []
  p.on('pageerror', (e) => errs.push(e.message))
  await p.addInitScript(() => localStorage.setItem('pumpchad.chadverse.save', JSON.stringify({ version: 2, character: null, progress: {}, settings: { quality: 'low', muted: true } })))
  await p.goto(BASE)
  await p.click('[data-testid=enter-muted]')
  await p.waitForSelector('[role=tablist]')
  await p.waitForTimeout(1200)
  check((await p.locator('[data-testid^=species-]').count()) >= 3, 'three species cards')
  check((await p.locator('canvas').count()) === 1, 'one renderer canvas only (no second heavy scene)')
  check(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'no horizontal overflow')
  const sel = () => p.evaluate(() => [...document.querySelectorAll('[role=radio][data-testid^=species-]')].find((e) => e.getAttribute('aria-checked') === 'true')?.getAttribute('data-testid'))
  check((await sel()) === 'species-pumpkin', 'PumpChad selected first')
  if (name === 'phone') await p.locator('[data-testid=species-skeleton]').tap()
  else await p.locator('[data-testid=species-skeleton]').click()
  await p.waitForTimeout(500)
  check((await sel()) === 'species-skeleton', 'a card selects (' + (name === 'phone' ? 'touch' : 'mouse') + ')')
  await p.locator('[data-testid=species-skeleton]').focus()
  await p.keyboard.press('ArrowRight')
  await p.waitForTimeout(400)
  check((await sel()) === 'species-demon', 'ArrowRight moves to the next species (keyboard)')
  await p.keyboard.press('ArrowLeft')
  await p.keyboard.press('ArrowLeft')
  await p.waitForTimeout(400)
  check((await sel()) === 'species-pumpkin', 'ArrowLeft cycles back (wraps)')
  await p.getByRole('button', { name: 'Next species' }).click()
  await p.waitForTimeout(300)
  check((await sel()) === 'species-skeleton', 'the arrow buttons cycle too')
  const enter = p.locator('[data-testid=enter-world]')
  const bb = await enter.boundingBox()
  check(bb && bb.height >= 44 && bb.y + bb.height <= p.viewportSize().height, `the enter button is reachable (${bb?.height.toFixed(0)} px tall, bottom ${bb && (bb.y + bb.height).toFixed(0)} of ${p.viewportSize().height})`)
  // the name is required: entering with no name goes to the Name tab; with a name it enters
  await enter.click()
  await p.waitForTimeout(400)
  check((await p.locator('#chad-name').count()) === 1, 'entering without a name opens the Name tab')
  await p.fill('#chad-name', 'Selector')
  await enter.click()
  await p.waitForFunction(() => window.__chadverse?.phase === 'world', null, { timeout: 120000 }).catch(() => {})
  check((await p.evaluate(() => window.__chadverse?.phase)) === 'world', 'enter leads into the world')
  const saved = await p.evaluate(() => JSON.parse(localStorage.getItem('pumpchad.chadverse.save')).character?.appearance?.species)
  check(saved === 'skeleton', `the chosen species is saved (${saved})`)
  check((await p.locator('canvas').count()) === 1, 'still one canvas in the world (the stage was released)')
  check(!errs.length, `no page errors ${JSON.stringify(errs.slice(0, 2))}`)
  await ctx.close()
}
console.log(fails ? `${fails} FAILED` : 'ALL PASS')
await b.close()
process.exit(fails ? 1 : 0)
