// Bench sitting + seed pick-up: real library clips (Sitting_Enter / Sitting_Idle_Loop / Sitting_Exit, Farm_Harvest).
//   SHOTS=dir node scripts/sit-test.mjs
import { chromium } from 'playwright'
const out = process.env.SHOTS
const b = await chromium.launch({ executablePath: process.env.LOCALAPPDATA + '/ms-playwright/chromium-1228/chrome-win64/chrome.exe' })
const p = await b.newPage({ viewport: { width: 1100, height: 760 } })
const errs = []
let fails = 0
const check = (ok, msg) => { console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${msg}`); if (!ok) fails++ }
p.on('pageerror', (e) => errs.push(e.message))
p.on('console', (m) => m.type() === 'error' && errs.push(m.text().slice(0, 200)))
await p.goto(process.env.URL || 'http://localhost:4318/chadverse/', { waitUntil: 'networkidle' })
await p.evaluate(() => localStorage.clear())
await p.reload({ waitUntil: 'networkidle' })
await p.click('[data-testid=enter-muted]')
await p.waitForSelector('[role=tablist]')
await p.getByRole('tab', { name: 'Name' }).click()
await p.fill('#chad-name', 'Sit Test')
await p.getByRole('button', { name: /Enter Chad Square/ }).click()
await p.waitForFunction(() => window.__chadverse?.phase === 'world' && window.__chadverse.playerInspect(), null, { timeout: 60000 })
await p.waitForTimeout(1500)
const W = () => p.evaluate(() => window.__chadverse.world())
const seat = () => p.evaluate(() => window.__chadverse.seat())
const orbit = async (dx, dy = 0) => {
  await p.mouse.move(550, 400)
  await p.mouse.down()
  await p.mouse.move(550 + dx, 400 + dy, { steps: 8 })
  await p.mouse.up()
}

// ── bench 0 at (-9.6, 32.1), seat faces south (+z)
await p.evaluate(() => window.__chadverse.teleport(-9.6, 32.9, Math.PI))
await p.waitForTimeout(700)
const prompt = await p.evaluate(() => document.body.innerText.includes('Sit and watch Chad City'))
check(prompt, 'bench shows "Sit and watch Chad City" prompt')
await p.keyboard.press('e')
await p.waitForTimeout(250)
let s = await seat()
check(s && s.phase === 'enter', `pressing E starts the sit-down clip (${JSON.stringify(s)})`)
await p.waitForTimeout(400)
await orbit(-260, -30)
await p.screenshot({ path: `${out}/sit-enter.jpg`, quality: 80 })
await p.waitForFunction(() => window.__chadverse.seat()?.phase === 'sit', null, { timeout: 8000 }).catch(() => {})
s = await seat()
check(s && s.phase === 'sit', 'settles into the seated loop')
await p.waitForTimeout(800)
await p.screenshot({ path: `${out}/sit-side.jpg`, quality: 80 })
await orbit(-300, 0)
await p.waitForTimeout(500)
await p.screenshot({ path: `${out}/sit-front.jpg`, quality: 80 })
// moving while seated stands up (doesn't teleport or slide)
const before = await W()
await p.keyboard.down('w')
await p.waitForTimeout(300)
await p.keyboard.up('w')
s = await seat()
check(s && s.phase === 'exit', 'pressing a move key plays the stand-up clip')
const mid = await W()
check(Math.hypot(mid.x - before.x, mid.z - before.z) < 0.05, 'no sliding while standing up')
await p.waitForFunction(() => window.__chadverse.seat() === null, null, { timeout: 8000 }).catch(() => {})
check((await seat()) === null, 'free to move again after standing')
await p.keyboard.down('w')
await p.waitForTimeout(600)
await p.keyboard.up('w')
const after = await W()
check(Math.hypot(after.x - mid.x, after.z - mid.z) > 0.4, 'walks away normally')

// ── seed pick-up
await p.evaluate(() => window.__chadverse.teleport(-20.4, 25.6, Math.PI))
await p.waitForTimeout(700)
await p.keyboard.press('e')
await p.waitForTimeout(350)
const a1 = await W()
await p.keyboard.down('w')
await p.waitForTimeout(300)
await p.screenshot({ path: `${out}/pickup.jpg`, quality: 80 })
await p.keyboard.up('w')
const a2 = await W()
check(Math.hypot(a2.x - a1.x, a2.z - a1.z) < 0.05, 'movement locked while picking up the seed')
await p.waitForTimeout(1600)
const sv = await p.evaluate(() => window.__chadverse.save().progress.discoveries)
check(sv.includes('seed_1'), 'seed collected + saved')
console.log('errors:', errs)
check(errs.length === 0, 'no console errors')
console.log(fails ? `${fails} FAILURE(S)` : 'ALL CHECKS PASSED')
await b.close()
