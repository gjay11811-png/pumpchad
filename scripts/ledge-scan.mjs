// LEDGE SCAN (offline, run when the town's geometry changes): find every box collider whose TOP is a real, flat, reachable surface and write them to
// src/game/scenes/world/ledgeData.ts. A collider qualifies when it is 0.95-3.6 m tall, its top is at least 0.5 m across, it is inside the open (launch) village, and rays dropped onto
// its top from above hit visible scenery at (almost) exactly that height with an upward-facing surface on at least two thirds of nine sample points — so a pitched roof, a
// canopy, a tree or an invisible helper box never becomes a "ledge". The yard (it has its own hand-authored platforms) and the Valley Gate area are excluded.
//   node scripts/ledge-scan.mjs
import { chromium } from 'playwright'
import { writeFileSync } from 'node:fs'
const b = await chromium.launch({ executablePath: process.env.LOCALAPPDATA + '/ms-playwright/chromium-1228/chrome-win64/chrome.exe', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-gpu-watchdog'] })
const p = await b.newPage({ viewport: { width: 800, height: 500 } })
await p.addInitScript(() => localStorage.setItem('pumpchad.chadverse.save', JSON.stringify({ version: 2, character: null, progress: { discoveries: ['intro_seen'], xp: 800 }, settings: { quality: 'low', muted: true } })))
await p.goto(`http://localhost:${process.env.PORT || 5180}/chadverse/?sky=day`)
await p.click('[data-testid=enter-muted]')
await p.waitForSelector('[role=tablist]')
await p.getByRole('tab', { name: 'Name' }).click()
await p.fill('#chad-name', 'Rider')
await p.getByRole('button', { name: /Enter Chad Square/ }).click()
await p.waitForFunction(() => window.__chadverse?.phase === 'world' && window.__chadverse.world(), null, { timeout: 120000 })
const all = await p.evaluate(() => window.__chadverse.allColliders())
const inYard = (x, z) => x > -243 && x < -169 && z > -21 && z < 28
const cands = all.filter((c) => c[0] === 1).map((c) => ({ minX: c[1], maxX: c[2], minZ: c[3], maxZ: c[4], h: c[5] })).filter((c) => {
  const w = c.maxX - c.minX
  const d = c.maxZ - c.minZ
  const cx = (c.minX + c.maxX) / 2
  const cz = (c.minZ + c.maxZ) / 2
  return c.h >= 0.95 && c.h <= 3.6 && Math.min(w, d) >= 0.5 && Math.max(w, d) >= 0.9 && cz < 70 && !inYard(cx, cz) && !(cx > 66 && cz > 60)
})
console.log('candidates', cands.length, 'of', all.length)
const out = []
const rejected = []
for (const c of cands) {
  const w = c.maxX - c.minX
  const d = c.maxZ - c.minZ
  const ix = Math.min(0.15, w * 0.25)
  const iz = Math.min(0.15, d * 0.25)
  let ok = 0
  let n = 0
  const ys = []
  for (const fx of [0, 0.5, 1]) for (const fz of [0, 0.5, 1]) {
    const x = c.minX + ix + (w - 2 * ix) * fx
    const z = c.minZ + iz + (d - 2 * iz) * fz
    const r = await p.evaluate(([x, z, y]) => window.__chadverse.rayDown(x, z, y), [x, z, c.h + 2.5])
    n++
    if (r) ys.push(r.y)
    if (r && Math.abs(r.y - c.h) <= 0.18 && r.ny > 0.85) ok++
  }
  const rec = { ...c, ok, n, ys: ys.slice(0, 3) }
  if (ok / n >= 2 / 3) out.push(rec)
  else rejected.push(rec)
}
console.log('flat, reachable tops:', out.length, ' rejected:', rejected.length)
for (const r of out) console.log(`  OK  x ${r.minX.toFixed(1)}..${r.maxX.toFixed(1)} z ${r.minZ.toFixed(1)}..${r.maxZ.toFixed(1)} top ${r.h.toFixed(2)}  (${r.ok}/${r.n})`)
for (const r of rejected.slice(0, 40)) console.log(`  no  x ${r.minX.toFixed(1)}..${r.maxX.toFixed(1)} z ${r.minZ.toFixed(1)}..${r.maxZ.toFixed(1)} h ${r.h.toFixed(2)} (${r.ok}/${r.n}) saw ${r.ys.join(',')}`)
const rows = out.map((r) => `  [${r.minX}, ${r.maxX}, ${r.minZ}, ${r.maxZ}, ${r.h}],`).join('\n')
writeFileSync('src/game/scenes/world/ledgeData.ts', `/**
 * GENERATED by scripts/ledge-scan.mjs — do not edit by hand. Box colliders whose top was verified (rays onto the visible scenery) to be a real, flat, reachable surface.
 * The world turns each into a climbable / hangable platform and drops its plain collider. Re-run the scan whenever the town's geometry changes.
 * [minX, maxX, minZ, maxZ, top]
 */
export const WORLD_LEDGES: [number, number, number, number, number][] = [
${rows}
]
`)
await b.close()
